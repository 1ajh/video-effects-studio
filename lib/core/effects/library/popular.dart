/// More of the Logo Editing Wiki's popular effects and G-Majors, from the
/// recipes on their wiki pages. AVS Video Editor pitch-shift rates are
/// converted to semitones (AVS 160 = −8.14, AVS 54 = +10.67, matching the
/// Vegas values the wiki gives alongside them).
const _wiki = 'Logo Editing Wiki';

/// Semitones for an AVS Video Editor pitch-shift rate (100 = unchanged).
double avsPitch(double rate) => -12 * math.log(rate / 100) / math.ln2;

/// Pinch/Punch: [amount] −1 (maximum punch) … +1 (maximum pinch).
String _pinchPunch(double amount) => radial(1 - amount * 0.6);

/// Colorful Out effects: the picture through a black → [hex] gradient map.
String _colorOut(String hex) => gradientMap('000000', hex);

/// Splits the frame into quarters and swaps them diagonally (AVS "Puzzle").
String _puzzle(FilterGraph g, String input) {
  final even = g.v(input, 'scale=trunc(iw/2)*2:trunc(ih/2)*2');
  final s = g.split(even, 4);
  String q(int i, String x, String y) => g.v(s[i], 'crop=iw/2:ih/2:$x:$y');
  final tl = q(0, '0', '0'), tr = q(1, 'iw', '0'), bl = q(2, '0', 'ih'), br = q(3, 'iw', 'ih');
  return g.join([br, bl, tr, tl], 'xstack=inputs=4:layout=0_0|w0_0|0_h0|w0_h0');
}

